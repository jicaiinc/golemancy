/**
 * Pack runtime/ and server/ resources into a single .tar.gz archive for Windows.
 *
 * Problem: NSIS installer extracts ~20,000 individual files, each scanned by
 * Windows Defender in real time, making installation extremely slow.
 *
 * Solution: Pack everything into one archive. NSIS installs just this file
 * (instant). Electron extracts it on first launch with a progress UI.
 *
 * Output:
 *   apps/desktop/resources/resources-archive.tar.gz   (the archive)
 *   apps/desktop/resources/resources-archive.json      (metadata for progress tracking)
 *   apps/desktop/electron-builder.win.yml              (auto-generated config)
 */

import { execFileSync } from 'node:child_process'
import { readdir, readFile, stat, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const DESKTOP = join(ROOT, 'apps/desktop')
const RESOURCES = join(DESKTOP, 'resources')
const ARCHIVE_PATH = join(RESOURCES, 'resources-archive.tar.gz')
const META_PATH = join(RESOURCES, 'resources-archive.json')
const WIN_CONFIG_PATH = join(DESKTOP, 'electron-builder.win.yml')
const BASE_CONFIG_PATH = join(DESKTOP, 'electron-builder.yml')

// ── Step 1: Count files and bytes ──────────────────────────────────────────

async function countDir(dirPath) {
  let files = 0
  let bytes = 0

  const entries = await readdir(dirPath, { withFileTypes: true })
  for (const entry of entries) {
    const fullPath = join(dirPath, entry.name)
    if (entry.isDirectory()) {
      const sub = await countDir(fullPath)
      files += sub.files
      bytes += sub.bytes
    } else {
      files++
      const s = await stat(fullPath)
      bytes += s.size
    }
  }

  return { files, bytes }
}

// ── Step 2: Create tar.gz archive ──────────────────────────────────────────

function createArchive() {
  console.log('Creating resources archive...')
  // tar czf from the resources/ directory, including runtime/ and server/
  execFileSync('tar', [
    'czf', ARCHIVE_PATH,
    '-C', RESOURCES,
    'runtime',
    'server',
  ], { stdio: 'inherit' })

  console.log('Archive created:', ARCHIVE_PATH)
}

// ── Step 3: Write metadata ─────────────────────────────────────────────────

async function writeMetadata() {
  const runtime = await countDir(join(RESOURCES, 'runtime'))
  const server = await countDir(join(RESOURCES, 'server'))

  const desktopPkg = JSON.parse(await readFile(join(DESKTOP, 'package.json'), 'utf8'))

  const meta = {
    totalFiles: runtime.files + server.files,
    totalBytes: runtime.bytes + server.bytes,
    version: desktopPkg.version,
    runtime: { files: runtime.files, bytes: runtime.bytes },
    server: { files: server.files, bytes: server.bytes },
  }

  await writeFile(META_PATH, JSON.stringify(meta, null, 2) + '\n')
  console.log(`Metadata: ${meta.totalFiles} files, ${Math.round(meta.totalBytes / 1024 / 1024)} MB`)
  return meta
}

// ── Step 4: Generate electron-builder.win.yml ──────────────────────────────

async function generateWinConfig() {
  const baseConfig = await readFile(BASE_CONFIG_PATH, 'utf8')

  // Replace the extraResources block.
  // The block starts with "extraResources:" and continues with lines starting
  // with "  -" or "    " until a line that doesn't match (next top-level key).
  const winExtraResources = `extraResources:
  - from: resources/resources-archive.tar.gz
    to: resources-archive.tar.gz
  - from: resources/resources-archive.json
    to: resources-archive.json
`

  const lines = baseConfig.split('\n')
  const result = []
  let inExtraResources = false

  for (const line of lines) {
    if (line.startsWith('extraResources:')) {
      inExtraResources = true
      result.push(winExtraResources)
      continue
    }

    if (inExtraResources) {
      // Still inside the extraResources block if line starts with whitespace
      // or is empty (blank lines between entries)
      if (line.match(/^\s/) || line === '') {
        continue
      }
      // Reached next top-level key
      inExtraResources = false
    }

    result.push(line)
  }

  const header = '# AUTO-GENERATED by scripts/pack-resources.mjs — do not edit manually.\n'
    + '# Based on electron-builder.yml with extraResources replaced for Windows archive mode.\n\n'

  await writeFile(WIN_CONFIG_PATH, header + result.join('\n'))
  console.log('Generated:', WIN_CONFIG_PATH)
}

// ── Main ───────────────────────────────────────────────────────────────────

async function main() {
  console.log('\n=== pack-resources ===\n')

  // Verify source directories exist
  for (const dir of ['runtime', 'server']) {
    try {
      await stat(join(RESOURCES, dir))
    } catch {
      console.error(`ERROR: ${dir}/ not found in ${RESOURCES}`)
      console.error('Run download-runtime.sh and bundle-server.mjs first.')
      process.exit(1)
    }
  }

  const meta = await writeMetadata()
  createArchive()

  const archiveStat = await stat(ARCHIVE_PATH)
  const archiveMB = Math.round(archiveStat.size / 1024 / 1024)
  const originalMB = Math.round(meta.totalBytes / 1024 / 1024)
  console.log(`Archive size: ${archiveMB} MB (original: ${originalMB} MB, ratio: ${Math.round(archiveMB / originalMB * 100)}%)`)

  await generateWinConfig()

  console.log('\n=== pack-resources done ===\n')
}

main()
